import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { createReadStream } from "node:fs";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve, sep } from "node:path";
import type { Readable } from "node:stream";
import { config } from "../config";
import type { Tx } from "../db/database";

/**
 * File storage behind a small interface so callers never know where blobs live:
 * local disk for development and long-running servers, S3-compatible object storage
 * (R2, S3, MinIO) for serverless hosts, whose disk is not kept between requests.
 * Keys are generated by the API (`tenants/<tenantId>/<id>`), never taken from users.
 */
export interface FileStorage {
  /** "local" | "s3" — shown on the platform System page */
  readonly driver: string;
  put(key: string, data: Buffer): Promise<void>;
  read(key: string): Promise<Readable>;
  remove(key: string): Promise<void>;
}

export class LocalFileStorage implements FileStorage {
  readonly driver = "local";
  private readonly root = resolve(config().FILE_STORAGE_DIR);

  private path(key: string) {
    const full = resolve(join(this.root, key));
    // Defence in depth against path traversal even though keys are server-generated
    if (!full.startsWith(this.root + sep)) throw new Error(`Invalid storage key: ${key}`);
    return full;
  }

  async put(key: string, data: Buffer) {
    const path = this.path(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, data, { flag: "wx" });
  }

  async read(key: string) {
    return createReadStream(this.path(key));
  }

  async remove(key: string) {
    await rm(this.path(key), { force: true });
  }
}

export class S3FileStorage implements FileStorage {
  readonly driver = "s3";
  private readonly bucket: string;
  private readonly client: S3Client;

  constructor() {
    const c = config();
    this.bucket = c.S3_BUCKET!;
    this.client = new S3Client({
      region: c.S3_REGION,
      endpoint: c.S3_ENDPOINT,
      forcePathStyle: c.S3_FORCE_PATH_STYLE,
      credentials: { accessKeyId: c.S3_ACCESS_KEY_ID!, secretAccessKey: c.S3_SECRET_ACCESS_KEY! },
    });
  }

  async put(key: string, data: Buffer) {
    await this.client.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: data, ContentType: "application/octet-stream" }));
  }

  async read(key: string) {
    const res = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    // In Node the SDK returns the body as a Readable stream
    return res.Body as Readable;
  }

  async remove(key: string) {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

export const createFileStorage = (): FileStorage => (config().STORAGE_DRIVER === "s3" ? new S3FileStorage() : new LocalFileStorage());

/**
 * Deletes the file records attached to entities and returns their storage keys;
 * callers remove the blobs after the transaction commits.
 */
export async function detachFiles(tx: Tx, tenantId: string, entityType: "task" | "chat", entityIds: string[]) {
  const files = await tx.fileObject.find({ tenantId, entityType, entityId: { $in: entityIds } }, { projection: { key: 1 } });
  await tx.fileObject.deleteMany({ tenantId, entityType, entityId: { $in: entityIds } });
  return files.map((f) => f.key);
}
